use panel_common::configuration::{
    ApplyInput, ClientInput, ClientView, ConfigRef, CreatedClient, InboundInput, InboundView,
    RevisionView,
};
use panel_common::traffic::{
    ClientCounter, ClientTraffic, NodeTraffic, TrafficBucket, TrafficReport, TrafficSample,
};
use panel_common::xray::XrayApiInput;
use panel_common::{
    AdminUser, AgentInfo, AuditEntry, AuditMetadata, ByteUsage, EnrollmentInput,
    EnrollmentResponse, HealthResponse, HealthStatus, LoginRequest, ManagedService, MetricIssue,
    MetricName, MetricReason, MetricsSnapshot, NetworkUsage, Node, NodeInput, NodeMetrics,
    NodeMetricsSummary, NodeSummary, ServiceError, ServiceQuery, ServiceReport, SessionResponse,
    TaskCommand, TaskInput, TaskOperation, TaskOutcome, TaskRecord, XrayError, XrayOperation,
    XrayRelease, XrayReport, XrayResult, XrayVersion,
};
use std::{env, error::Error, fs, path::Path};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let cfg = Config::default();
    let mut output = "// Generated by panel-common; run pnpm run types in web/.\n".to_owned();
    for declaration in [
        HealthStatus::decl(&cfg),
        HealthResponse::decl(&cfg),
        LoginRequest::decl(&cfg),
        AdminUser::decl(&cfg),
        SessionResponse::decl(&cfg),
        NodeInput::decl(&cfg),
        Node::decl(&cfg),
        AuditMetadata::decl(&cfg),
        AuditEntry::decl(&cfg),
        EnrollmentInput::decl(&cfg),
        EnrollmentResponse::decl(&cfg),
        AgentInfo::decl(&cfg),
        TaskOperation::decl(&cfg),
        TaskInput::decl(&cfg),
        TaskCommand::decl(&cfg),
        TaskOutcome::decl(&cfg),
        TaskRecord::decl(&cfg),
        ByteUsage::decl(&cfg),
        ManagedService::decl(&cfg),
        MetricName::decl(&cfg),
        MetricReason::decl(&cfg),
        MetricIssue::decl(&cfg),
        MetricsSnapshot::decl(&cfg),
        NetworkUsage::decl(&cfg),
        NodeMetrics::decl(&cfg),
        NodeMetricsSummary::decl(&cfg),
        NodeSummary::decl(&cfg),
        ServiceError::decl(&cfg),
        ServiceReport::decl(&cfg),
        ServiceQuery::decl(&cfg),
        XrayVersion::decl(&cfg),
        XrayRelease::decl(&cfg),
        XrayOperation::decl(&cfg),
        XrayReport::decl(&cfg),
        XrayError::decl(&cfg),
        XrayResult::decl(&cfg),
        XrayApiInput::decl(&cfg),
        ConfigRef::decl(&cfg),
        InboundInput::decl(&cfg),
        InboundView::decl(&cfg),
        ClientInput::decl(&cfg),
        ClientView::decl(&cfg),
        CreatedClient::decl(&cfg),
        RevisionView::decl(&cfg),
        ApplyInput::decl(&cfg),
        ClientCounter::decl(&cfg),
        TrafficSample::decl(&cfg),
        TrafficReport::decl(&cfg),
        TrafficBucket::decl(&cfg),
        ClientTraffic::decl(&cfg),
        NodeTraffic::decl(&cfg),
    ] {
        output.push_str(&declaration.replacen("type ", "export type ", 1));
        output.push('\n');
    }
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../web/src/types");
    let path = directory.join("generated.ts");
    if env::args().any(|arg| arg == "--check") {
        if fs::read_to_string(path)? != output {
            return Err("TypeScript contract is stale; run pnpm run types in web/".into());
        }
    } else {
        fs::create_dir_all(directory)?;
        fs::write(path, output)?;
    }
    Ok(())
}
